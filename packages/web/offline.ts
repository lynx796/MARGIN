import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

// Production build finishing (spec §11, phase 6), run once all files are written:
//
// 1. Subresource Integrity: every <script src> and <link href> in index.html gets `integrity`.
//    Chunks loaded later (dynamic imports, workers, WASM) cannot carry it; they are same-origin and
//    covered by `script-src 'self'`.
// 2. Service worker: `sw.js` precaches every file of the build, so after the first visit the app
//    works without network. Its cache name is a hash of all files, so a new build replaces the cache.

/** All files under `dir`, as `/`-separated paths relative to it, sorted. */
function walk(dir: string, root = dir): string[] {
  const out: string[] = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(abs, root));
    else if (e.isFile()) out.push(relative(root, abs).split(sep).join('/'));
  }
  return out.sort();
}

/** `integrity` attributes for the tags Vite wrote into index.html. */
export function addIntegrity(html: string, read: (path: string) => Uint8Array): string {
  return html.replace(/<(script|link)\b([^>]*?)\s(src|href)="([^"]+)"([^>]*)>/g, (tag, name: string, before: string, attr: string, url: string, after: string) => {
    if (/^(?:[a-z]+:|\/\/)/i.test(url) || /\bintegrity=/.test(tag)) return tag;
    if (name === 'link' && !/\brel="(?:stylesheet|modulepreload)"/.test(tag)) return tag;
    const hash = createHash('sha384').update(read(url.replace(/^\.?\//, ''))).digest('base64');
    return `<${name}${before} ${attr}="${url}" integrity="sha384-${hash}"${after}>`;
  });
}

export function serviceWorkerSource(version: string, files: string[]): string {
  return `// Generated by the build (packages/web/offline.ts). Precaches the app; never touches /api/ or other origins.
const CACHE = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(['./', ...files.map((f) => './' + f)])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('margin-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (req.mode === 'navigate') {
    // The page itself: the network first (a new deployment is picked up), the cached copy offline.
    e.respondWith(fetch(req).catch(() => caches.match(new URL('./', self.registration.scope).href, { ignoreVary: true })));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
}

export function offline(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'margin-offline',
    apply: 'build',
    configResolved(c) {
      config = c;
    },
    closeBundle() {
      const out = resolve(config.root, config.build.outDir);
      const index = join(out, 'index.html');
      writeFileSync(index, addIntegrity(readFileSync(index, 'utf8'), (p) => readFileSync(join(out, p))));
      const files = walk(out).filter((f) => f !== 'sw.js');
      const hash = createHash('sha256');
      for (const f of files) hash.update(f).update('\0').update(readFileSync(join(out, f))).update('\0');
      writeFileSync(join(out, 'sw.js'), serviceWorkerSource(`margin-${hash.digest('hex').slice(0, 16)}`, files));
    },
  };
}

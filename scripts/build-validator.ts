// Generates packages/core/src/model/validator.generated.js: the annotation schema compiled to
// standalone code at build time, so no runtime code generation (`new Function`) is needed. The web
// app's CSP forbids 'unsafe-eval' (spec §11).
// Run: pnpm validator:build   (a test fails if the committed file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

export function generate(): string {
  const root = new URL('../', import.meta.url);
  const schema = JSON.parse(readFileSync(new URL('schema/annot.schema.json', root), 'utf8'));
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
  const validate = ajv.compile(schema);
  // Standalone output still `require`s one runtime helper, which is not valid in an ES module: inline it.
  const ucs2length = `(function (str) { const len = str.length; let length = 0; let pos = 0; while (pos < len) { length++; let value = str.charCodeAt(pos++); if (value >= 0xd800 && value <= 0xdbff && pos < len) { value = str.charCodeAt(pos); if ((value & 0xfc00) === 0xdc00) pos++; } } return length; })`;
  const code = standaloneCode(ajv, validate).replace('require("ajv/dist/runtime/ucs2length").default', ucs2length);
  if (code.includes('require(')) throw new Error('standalone validator still contains require()');
  return '// @ts-nocheck\n// Generated by scripts/build-validator.ts from schema/annot.schema.json. Do not edit.\n' + code;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const target = new URL('../packages/core/src/model/validator.generated.js', import.meta.url);
  writeFileSync(target, generate());
  console.log(`wrote ${target.pathname}`);
}
